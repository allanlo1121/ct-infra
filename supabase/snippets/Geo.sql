create table if not exists proj.risk_solutions (
  id uuid primary key default gen_random_uuid(),

  code text null,
  name text not null,

  applicable_conditions text null,
  summary text null,

  source_risk_id uuid null
    references proj.tunnel_risks(id)
    on delete set null,

  remark text null,

  is_template boolean not null default false,
  is_disabled boolean not null default false,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint ck_risk_solutions_name_not_blank
    check (btrim(name) <> ''),

  constraint ck_risk_solutions_code_not_blank
    check (code is null or btrim(code) <> '')
);

create unique index if not exists uq_risk_solutions_code
  on proj.risk_solutions(code)
  where code is not null;


create table if not exists proj.risk_solution_items (
  id uuid primary key default gen_random_uuid(),

  solution_id uuid not null
    references proj.risk_solutions(id)
    on delete cascade,

  item_no smallint not null,
  title text null,
  content text not null,

  category text null,

  is_required boolean not null default true,
  sort_order smallint not null default 0,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint uq_risk_solution_items_no
    unique (solution_id, item_no),

  constraint ck_risk_solution_items_content_not_blank
    check (btrim(content) <> ''),

  constraint ck_risk_solution_items_item_no
    check (item_no > 0)
);

create or replace view app.v_tunnel_risks_active
with (security_invoker = true)
as
with active_assignments as (
  select distinct on (ta.tunnel_id)
    ta.tunnel_id,
    ta.tbm_id,
    ta.start_date
  from tbm.tbm_assignments ta
  where ta.end_date is null
  order by
    ta.tunnel_id,
    ta.start_date desc nulls last
)
select
  risk.id as risk_id,

  risk.tunnel_id,
  aa.tbm_id,
  

  risk.name as risk_name,
  risk.risk_level,

  risk.start_chainage,
  risk.end_chainage,
  tunnel.advance_direction,

  risk.burial_depth,


  risk.geo_class_id,
  geo.name as geo_class_name,
  geo.layer as geo_class_layer,

  risk.geo_rock_class_id,
  rock.code as geo_rock_class_code,
  rock.name as geo_rock_class_name,

  risk.description,
  risk.remark,

  coalesce(solution_data.solutions, '[]'::jsonb) as solutions,

  risk.created_at,
  risk.updated_at

from active_assignments aa

join proj.tunnel_risks risk
  on risk.tunnel_id = aa.tunnel_id
 and risk.deleted_at is null

join proj.tunnels tunnel
  on tunnel.id = risk.tunnel_id
 and tunnel.deleted_at is null

left join proj.geo_classes geo
  on geo.id = risk.geo_class_id

left join proj.geo_rock_classes rock
  on rock.id = risk.geo_rock_class_id

left join lateral (
  select
    jsonb_agg(
      jsonb_build_object(
        'id', solution.id,
        'code', solution.code,
        'name', solution.name,
        'applicableConditions', solution.applicable_conditions,
        'summary', solution.summary,
        'isPrimary', relation.is_primary,
        'items', coalesce(item_data.items, '[]'::jsonb)
      )
      order by
        relation.is_primary desc,
        solution.created_at,
        solution.id
    ) as solutions

  from proj.tunnel_risk_solutions relation

  join proj.risk_solutions solution
    on solution.id = relation.solution_id
   and solution.is_disabled = false

  left join lateral (
    select
      jsonb_agg(
        jsonb_build_object(
          'id', item.id,
          'itemNo', item.item_no,
          'title', item.title,
          'content', item.content,
          'category', item.category,
          'isRequired', item.is_required
        )
        order by
          item.sort_order,
          item.item_no,
          item.id
      ) as items
    from proj.risk_solution_items item
    where item.solution_id = solution.id
  ) item_data on true

  where relation.risk_id = risk.id
) solution_data on true;